/**
 * Finding the line being spoken right now.
 *
 * Called on every animation frame while audio plays, against transcripts that
 * routinely run to several thousand segments — so it is a binary search, not a
 * scan. A linear pass over 4,000 cues at 120Hz is half a million comparisons a
 * second to move one highlight.
 *
 * The awkward part is not the search, it is the gaps. Caption files leave
 * silence between cues: music, a pause, the end of the episode. During a gap
 * nothing is being said, and the honest answer is "no line" — but a transcript
 * that keeps blanking its highlight between sentences reads as broken. So a gap
 * holds the previous line instead, which is also what a reader following along
 * expects: the last thing said stays lit until the next thing is said.
 */

import type { TranscriptSegment } from '@cue/types';

/**
 * Index of the segment covering `positionMs`, or the one most recently passed.
 *
 * Returns -1 only before the first cue begins. Segments must be sorted by
 * `startMs`, which `parseTranscript` guarantees.
 */
export function activeSegmentIndex(segments: TranscriptSegment[], positionMs: number): number {
  if (segments.length === 0) return -1;
  if (positionMs < segments[0]!.startMs) return -1;

  let low = 0;
  let high = segments.length - 1;
  let found = -1;

  // The last segment whose start is at or before the playhead. Written as a
  // "rightmost match" search rather than an exact one, because the playhead
  // spends most of its time between cue boundaries rather than on one.
  while (low <= high) {
    const mid = (low + high) >> 1;
    if (segments[mid]!.startMs <= positionMs) {
      found = mid;
      low = mid + 1;
    } else {
      high = mid - 1;
    }
  }

  return found;
}

/**
 * Where to seek to play a segment from its beginning.
 *
 * Nudged slightly earlier because cue starts are generated by aligning to the
 * first phoneme, and seeking exactly there routinely clips the opening
 * consonant — the difference between hearing "we sold it" and "e sold it".
 */
export const SEEK_LEAD_MS = 150;

export function seekTargetSec(segment: TranscriptSegment): number {
  return Math.max(0, segment.startMs - SEEK_LEAD_MS) / 1000;
}

/**
 * Segments whose text contains `query`, with their positions.
 *
 * Case-insensitive substring rather than anything cleverer: a listener
 * searching a transcript is looking for a phrase they just heard, not doing
 * information retrieval, and stemming would surprise them by matching words
 * they did not type.
 */
export function searchSegments(
  segments: TranscriptSegment[],
  query: string,
): TranscriptSegment[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return [];

  return segments.filter((segment) => segment.text.toLowerCase().includes(needle));
}
