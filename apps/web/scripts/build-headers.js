/**
 * Emits public/_headers, the response headers Cloudflare's asset server sends.
 *
 * This exists because of a gap that is invisible from the source: files under
 * public/ are served on Cloudflare by the ASSETS binding, which never reaches
 * the Next server — so `headers()` in next.config.ts does not run for them.
 * The block in there for /sw.js, the one whose comment explains at length why
 * a service worker must be uncacheable and must carry its own tight CSP, was
 * therefore sending nothing at all in the Cloudflare deployment. It applied on
 * Vercel, which is presumably why nobody noticed. Verified by curling the
 * worker: the header was simply absent.
 *
 * `_headers` is the asset server's own mechanism for this, and shipping it from
 * public/ means the build copies it into .open-next/assets alongside the file
 * it describes.
 *
 * Generated rather than hand-written for one reason: `connect-src` has to name
 * the API's origin, which comes from the environment at build time, and a
 * static file cannot interpolate one. The alternative — hardcoding a
 * production hostname into a checked-in file — is the kind of thing that is
 * still there and still wrong two deployments later.
 *
 * Regenerate with: npm run headers --workspace @cue/web
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildProvenance, provenanceHeaders } from '../../../scripts/build-provenance.js';

/**
 * The API's origin.
 *
 * Same parse-don't-interpolate reasoning as the identically-named functions in
 * next.config.ts and middleware.ts, and the same fallback as the clients in
 * lib/api.ts — a policy that names an origin the app never calls is merely
 * useless, but one that omits an origin the app does call is an outage.
 */
function apiOrigin() {
  try {
    return new URL(process.env['NEXT_PUBLIC_API_URL'] || 'http://localhost:8080').origin;
  } catch {
    return null;
  }
}

const api = apiOrigin();
const provenance = provenanceHeaders(buildProvenance()).map(({ key, value }) => `  ${key}: ${value}`).join('\n');

/**
 * The policy mirrors the /sw.js block in next.config.ts deliberately.
 *
 * Two copies is worse than one, but the two run on different infrastructure —
 * this one on Cloudflare's asset server, that one on whatever serves the app on
 * Vercel, which remains the rollback target. Deleting either leaves one
 * deployment unprotected. Change one and change the other.
 */
const content = `# GENERATED by scripts/build-headers.js — do not edit by hand.
#
# Cloudflare's asset server reads this; Next's headers() never sees requests
# for public/ files there. See the script for the full story.

/sw.js
  Content-Type: application/javascript; charset=utf-8
  Cache-Control: no-cache, no-store, must-revalidate
  Content-Security-Policy: default-src 'self'; script-src 'self'; connect-src 'self'${api ? ` ${api}` : ''}

# Applies to the block above too — Cloudflare unions the matching rules rather
# than letting the more specific one win, so anything repeated here would be
# sent twice.
/*
${provenance}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=63072000; includeSubDomains
`;

writeFileSync(join(import.meta.dirname, '../public/_headers'), content, 'utf8');
